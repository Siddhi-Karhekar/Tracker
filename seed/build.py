def resolve(ref: str) -> dict:
    """'discord:m025' → {ref, source, native_id, url}. native_id matches what ingestion stores."""
    parts = ref.split(":")
    if parts[0] == "discord":
        return {"ref": ref, "source": "discord", "seed_key": parts[1], "native_id": MSG_ID[parts[1]],
                "event_id": f"discord:message:{MSG_ID[parts[1]]}", "url": discord_url(parts[1])}
    if parts[0] == "notion":
        pid = NOTION_PAGE[parts[1]]
        return {"ref": ref, "source": "notion", "seed_key": parts[1], "native_id": pid,
                "event_id": f"notion:notion_page:{pid}"}
    if parts[0] == "github":
        kind, n = parts[1], int(parts[2])
        path = "issues" if kind == "issue" else "pull"
        etype = "issue" if kind == "issue" else "pull_request"
        return {"ref": ref, "source": "github", "native_id": str(n), "event_id": f"github:{etype}:{n}",
                "url": f"{GH}/{path}/{n}"}
    raise ValueError(ref)


def task_id_for_notion(key: str) -> str:
    t = next(t for t in S.NOTION_TASKS if t["key"] == key)
    return f"T-{t['issue']}" if t["issue"] else f"N-{NOTION_PAGE[key][:8]}"


def build_answer_key() -> dict:
    viva_id = task_id_for_notion("n13")
    blockers = []
    for m in S.MESSAGES:
        if m["label"] in ("blocker", "help_request"):
            solution = next((s for s in S.MESSAGES if s["resolves"] == m["key"]), None)
            blockers.append({
                "message": resolve(f"discord:{m['key']}"), "label": m["label"], "author": m["author"],
                "tasks": m["tasks"], "text": m["text"],
                "resolved_by": resolve(f"discord:{solution['key']}") | {"author": solution["author"]}
                if solution else None,
            })
    entity_links = [
        {"message": resolve(f"discord:{m['key']}"), "mention": m["mention"], "tasks": m["tasks"]}
        for m in S.MESSAGES if m["tasks"] and m["mention"]
    ]
    solutions = {}
    for m in S.MESSAGES:
        if m["label"] == "solution":
            solutions.setdefault(m["author"], []).append(MSG_ID[m["key"]])

    return {
        "scenario": "CampusEats demo team (fictional)",
        "snapshot_at": ist(S.SNAPSHOT_AT).isoformat(),
        "task_ids": {"github_issue_n": "T-<n>", "notion_only": "N-<first 8 chars of page id>",
                     "viva_preparation": viva_id},
        "discrepancies": [
            {**{k: d[k] for k in ("id", "type", "task", "severity", "summary")},
             "sides": [{"attribute": attr, "value": val, **resolve(ref)} for ref, attr, val in d["sides"]]}
            for d in S.DISCREPANCIES
        ],
        "consistent_tasks": [viva_id if t == "N-viva" else t for t in S.CONSISTENT_TASKS],
        "blockers": blockers,
        "entity_links": entity_links,
        "chat_claims": [
            {**c, "message": resolve(f"discord:{c['msg']}"), "evidence": [resolve(e) for e in c["evidence"]]}
            for c in S.CHAT_CLAIMS
        ],
        "solutions_by_member": solutions,
        "eval_questions": [{**q, "refs": [resolve(r) for r in q["refs"]]} for q in S.EVAL_QUESTIONS],
    }


def build_labels_csv(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["message_id", "seed_key", "channel", "timestamp", "author", "reply_to", "content",
                    "label", "task_ids", "mention", "resolves"])
        for m in sorted(S.MESSAGES, key=lambda m: m["ts"]):
            w.writerow([MSG_ID[m["key"]], m["key"], m["channel"], ist(m["ts"]).isoformat(), m["author"],
                        MSG_ID[m["reply_to"]] if m["reply_to"] else "", m["text"], m["label"],
                        "|".join(m["tasks"]), m["mention"] or "",
                        MSG_ID[m["resolves"]] if m["resolves"] else ""])


def main() -> None:
    (OUT).mkdir(parents=True, exist_ok=True)
    (OUT / "team.toml").write_text(build_team(), encoding="utf-8")
    issues, pulls, commits = build_github()
    write_json(OUT / "github" / "issues.json", issues)
    write_json(OUT / "github" / "pulls.json", pulls)
    write_json(OUT / "github" / "commits.json", commits)
    write_json(OUT / "github" / "repo.json", {"full_name": S.REPO, "html_url": GH})
    write_json(OUT / "notion" / "tasks.json", {
        "data_source_id": DATA_SOURCE_ID, "database_id": DATABASE_ID, "results": build_notion()})
    for ch, data in build_discord().items():
        write_json(OUT / "discord" / f"{ch}.json", data)
    build_labels_csv(OUT / "labels" / "discord_messages.csv")
    write_json(OUT / "answer_key.json", build_answer_key())
    print(f"Wrote demo data to {OUT}: {len(issues)} issues, {len(pulls)} PRs, "
          f"{len(commits)} commits, {len(S.NOTION_TASKS)} Notion tasks, {len(S.MESSAGES)} Discord messages, "
          f"{len(S.DISCREPANCIES)} planted discrepancies.")


if __name__ == "__main__":
    main()
