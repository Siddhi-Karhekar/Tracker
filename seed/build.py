NOTION_USER = {h: uid("notion-user", h) for h in S.MEMBERS}
DISCORD_USER = {h: str(1290000000000000100 + i) for i, h in enumerate(S.MEMBERS)}
CHANNEL_ID = {c: str(1290000000000001000 + i) for i, c in enumerate(S.CHANNELS)}
NOTION_PAGE = {t["key"]: uid("notion-page", t["key"]) for t in S.NOTION_TASKS}
DATA_SOURCE_ID = uid("notion-data-source", "tasks")
DATABASE_ID = uid("notion-database", "tasks")
MSG_ID = {m["key"]: snowflake(ist(m["ts"]), i) for i, m in enumerate(S.MESSAGES)}
MSG = {m["key"]: m for m in S.MESSAGES}
GH = f"https://github.com/{S.REPO}"


def build_team() -> str:
    lines = ["# Generated by seed/build.py — identities of the fictional demo team.\n"]
    for h, m in S.MEMBERS.items():
        lines += [
            f"[members.{h}]",
            f'display_name   = "{m["display_name"]}"',
            f'github         = "{m["github"]}"',
            f'notion_user_id = "{NOTION_USER[h]}"',
            f'discord_id     = "{DISCORD_USER[h]}"',
            f'discord_name   = "{m["discord_name"]}"',
            "opted_in       = true",
            "",
        ]
    return "\n".join(lines)


