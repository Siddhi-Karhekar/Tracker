"""Build data/demo/ from seed/scenario.py.

    python -m seed.build

Outputs (all deterministic, safe to commit):
  data/demo/team.toml                      identities for the fictional team
  data/demo/github/issues.json             [{issue, comments, events}]   (GitHub REST shapes)
  data/demo/github/pulls.json              [{pull, reviews, commits}]
  data/demo/github/commits.json            commits on main (merged PRs + direct pushes)
  data/demo/notion/tasks.json              pages from data_sources.query  (Notion API 2025-09-03)
  data/demo/discord/<channel>.json         DiscordChatExporter JSON, one file per channel
  data/demo/labels/discord_messages.csv    gold labels per message (start of the 300-message set)
  data/demo/answer_key.json                discrepancies, blockers, entity links, claims, questions
"""
from __future__ import annotations

import csv
import hashlib
import json
import re
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path

from seed import scenario as S

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "demo"
IST = timezone(timedelta(hours=5, minutes=30))
NS = uuid.UUID("6f1d2a4e-8c3b-4e57-9a0f-3c2b1d0e9f7a")
DISCORD_EPOCH_MS = 1420070400000
GUILD_ID = "1290000000000000001"


def ist(ts: str) -> datetime:
    return datetime.strptime(ts, "%Y-%m-%d %H:%M").replace(tzinfo=IST)


def utc_z(ts: str) -> str:
    return ist(ts).astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def notion_time(ts: str) -> str:
    return ist(ts).astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:00.000Z")


def snowflake(dt: datetime, seq: int = 0) -> str:
    ms = int(dt.timestamp() * 1000)
    return str(((ms - DISCORD_EPOCH_MS) << 22) | (seq & 0xFFF))


def uid(*parts: str) -> str:
    return str(uuid.uuid5(NS, "/".join(parts)))


def sha(*parts: str) -> str:
    return hashlib.sha1("/".join(parts).encode()).hexdigest()


def gh_user(handle: str) -> dict:
    return {"login": S.MEMBERS[handle]["github"], "type": "User"}


def write_json(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


