def slug(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "-", text).strip("-")


def build_notion() -> list:
    pages = []
    for t in S.NOTION_TASKS:
        pid = NOTION_PAGE[t["key"]]
        ts, who = t["edited"]
        pages.append({
            "object": "page",
            "id": pid,
            "created_time": notion_time(S.PROJECT_START),
            "last_edited_time": notion_time(ts),
            "created_by": {"object": "user", "id": NOTION_USER["siddhi"]},
            "last_edited_by": {"object": "user", "id": NOTION_USER[who]},
            "parent": {"type": "data_source_id", "data_source_id": DATA_SOURCE_ID, "database_id": DATABASE_ID},
            "archived": False,
            "in_trash": False,
            "url": f"https://www.notion.so/{slug(t['name'])}-{pid.replace('-', '')}",
            "properties": {
                "Name": {"id": "title", "type": "title",
                         "title": [{"type": "text", "text": {"content": t["name"]}, "plain_text": t["name"]}]},
                "Status": {"id": "status", "type": "status", "status": {"name": t["status"]}},
                "Assignee": {"id": "assignee", "type": "people",
                             "people": [{"object": "user", "id": NOTION_USER[t["assignee"]]}]},
                "Due": {"id": "due", "type": "date", "date": {"start": t["due"], "end": None}},
                "GitHub Issue": {"id": "ghissue", "type": "number", "number": t["issue"]},
            },
        })
    return pages


