def milestone(title: str | None) -> dict | None:
    if not title:
        return None
    number = list(S.MILESTONES).index(title) + 1
    return {"number": number, "title": title, "due_on": f"{S.MILESTONES[title]}T07:00:00Z", "state": "open"}


def build_github() -> tuple[list, list, list]:
    issues = []
    for it in S.ISSUES:
        n = it["number"]
        last = it["events"][-1] if it["events"] else None
        state = "closed" if last and last[2] == "closed" else "open"
        updated = max([it["created"]] + [e[0] for e in it["events"]] + [c[0] for c in it["comments"]])
        issue = {
            "number": n,
            "title": it["title"],
            "body": it["body"],
            "state": state,
            "state_reason": ("completed" if state == "closed" else ("reopened" if last else None)),
            "user": gh_user(it["author"]),
            "assignees": [gh_user(it["assignee"])] if it["assignee"] else [],
            "labels": [{"name": label} for label in it["labels"]],
            "milestone": milestone(it["milestone"]),
            "created_at": utc_z(it["created"]),
            "updated_at": utc_z(updated),
            "closed_at": utc_z(last[0]) if state == "closed" else None,
            "html_url": f"{GH}/issues/{n}",
        }
        comments = [
            {"id": int(sha("c", str(n), str(i))[:10], 16), "user": gh_user(who), "body": body,
             "created_at": utc_z(ts), "html_url": f"{GH}/issues/{n}#issuecomment-{i + 1}"}
            for i, (ts, who, body) in enumerate(it["comments"])
        ]
        events = [
            {"id": int(sha("e", str(n), str(i))[:10], 16), "event": kind, "actor": gh_user(who),
             "created_at": utc_z(ts)}
            for i, (ts, who, kind) in enumerate(it["events"])
        ]
        issues.append({"issue": issue, "comments": comments, "events": events})

    pulls, main_commits = [], []
    for pr in S.PULLS:
        n = pr["number"]
        commits = []
        for ts, msg in pr["commits"]:
            m = S.MEMBERS[pr["author"]]
            c = {
                "sha": sha("commit", str(n), ts, msg),
                "commit": {"message": msg, "author": {"name": m["display_name"],
                                                      "email": f'{m["github"]}@users.noreply.github.com',
                                                      "date": utc_z(ts)}},
                "author": gh_user(pr["author"]),
                "html_url": None,
            }
            c["html_url"] = f"{GH}/commit/{c['sha']}"
            commits.append(c)
        closes = " ".join(f"Closes #{i}." for i in pr["closes"])
        pull = {
            "number": n,
            "title": pr["title"],
            "body": f"{closes}\n\n{pr['title']}.",
            "state": "closed" if pr["merged"] else "open",
            "draft": pr.get("draft", False),
            "user": gh_user(pr["author"]),
            "created_at": utc_z(pr["created"]),
            "updated_at": utc_z(pr["merged"] or max([pr["created"]] + [r[0] for r in pr["reviews"]])),
            "merged_at": utc_z(pr["merged"]) if pr["merged"] else None,
            "closed_at": utc_z(pr["merged"]) if pr["merged"] else None,
            "merged_by": gh_user(pr["merged_by"]) if pr["merged_by"] else None,
            "head": {"ref": pr["branch"]},
            "base": {"ref": "main"},
            "html_url": f"{GH}/pull/{n}",
        }
        reviews = [
            {"id": int(sha("r", str(n), str(i))[:10], 16), "user": gh_user(who), "state": state, "body": body,
             "submitted_at": utc_z(ts), "html_url": f"{GH}/pull/{n}#pullrequestreview-{i + 1}"}
            for i, (ts, who, state, body) in enumerate(pr["reviews"])
        ]
        pulls.append({"pull": pull, "reviews": reviews, "commits": commits})
        if pr["merged"]:
            main_commits += commits

    for ts, who, msg in S.DIRECT_COMMITS:
        m = S.MEMBERS[who]
        s = sha("direct", ts, msg)
        main_commits.append({
            "sha": s,
            "commit": {"message": msg, "author": {"name": m["display_name"],
                                                  "email": f'{m["github"]}@users.noreply.github.com',
                                                  "date": utc_z(ts)}},
            "author": gh_user(who),
            "html_url": f"{GH}/commit/{s}",
        })
    main_commits.sort(key=lambda c: c["commit"]["author"]["date"])
    return issues, pulls, main_commits


