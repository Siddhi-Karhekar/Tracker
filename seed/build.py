def discord_author(handle: str) -> dict:
    return {"id": DISCORD_USER[handle], "name": S.MEMBERS[handle]["discord_name"], "discriminator": "0000",
            "nickname": S.MEMBERS[handle]["display_name"], "color": None, "isBot": False, "roles": [],
            "avatarUrl": "https://cdn.discordapp.com/embed/avatars/0.png"}


def discord_mentions(text: str) -> list:
    by_name = {m["discord_name"]: h for h, m in S.MEMBERS.items()}
    return [discord_author(by_name[n]) for n in re.findall(r"@([\w.]+)", text) if n in by_name]


def build_discord() -> dict[str, dict]:
    out = {}
    for ch in S.CHANNELS:
        msgs = sorted((m for m in S.MESSAGES if m["channel"] == ch), key=lambda m: m["ts"])
        rendered = []
        for m in msgs:
            item = {
                "id": MSG_ID[m["key"]],
                "type": "Reply" if m["reply_to"] else "Default",
                "timestamp": ist(m["ts"]).isoformat(timespec="milliseconds"),
                "timestampEdited": None,
                "callEndedTimestamp": None,
                "isPinned": False,
                "content": m["text"],
                "author": discord_author(m["author"]),
                "attachments": [], "embeds": [], "stickers": [], "reactions": [],
                "mentions": discord_mentions(m["text"]),
                "inlineEmojis": [],
            }
            if m["reply_to"]:
                item["reference"] = {"messageId": MSG_ID[m["reply_to"]], "channelId": CHANNEL_ID[ch],
                                     "guildId": GUILD_ID}
            rendered.append(item)
        out[ch] = {
            "guild": {"id": GUILD_ID, "name": S.GUILD, "iconUrl": ""},
            "channel": {"id": CHANNEL_ID[ch], "type": "GuildTextChat", "categoryId": "1290000000000000900",
                        "category": "Project", "name": ch, "topic": None},
            "dateRange": {"after": None, "before": None},
            "exportedAt": ist(S.SNAPSHOT_AT).isoformat(timespec="milliseconds"),
            "messages": rendered,
            "messageCount": len(rendered),
        }
    return out


def discord_url(key: str) -> str:
    return f"https://discord.com/channels/{GUILD_ID}/{CHANNEL_ID[MSG[key]['channel']]}/{MSG_ID[key]}"


